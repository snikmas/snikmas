// Scans content/posts/ and writes lib/posts/registry.generated.ts with static
// imports. Static imports are required so the bundler compiles each .mdx file.
// Re-run via `pnpm generate-posts` (also runs automatically before dev/build/test).
import { readdirSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const postsDir = path.join(root, 'content', 'posts')
const outFile = path.join(root, 'lib', 'posts', 'registry.generated.ts')
const LOCALES = ['en', 'zh']

const camel = (slug) => slug.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())

const slugs = readdirSync(postsDir)
  .filter((name) => statSync(path.join(postsDir, name)).isDirectory())
  .sort()

const imports = []
const entries = []

for (const slug of slugs) {
  const files = readdirSync(path.join(postsDir, slug))
  if (!files.includes('meta.ts')) {
    throw new Error(`content/posts/${slug}: missing meta.ts`)
  }
  const locales = LOCALES.filter((locale) => files.includes(`${locale}.mdx`))
  if (locales.length === 0) {
    throw new Error(`content/posts/${slug}: no .mdx body (expected en.mdx and/or zh.mdx)`)
  }

  const id = camel(slug)
  imports.push(`import ${id}Meta from '@/content/posts/${slug}/meta'`)
  const bodies = []
  for (const locale of locales) {
    const varName = `${id}${locale[0].toUpperCase()}${locale.slice(1)}`
    imports.push(`import ${varName} from '@/content/posts/${slug}/${locale}.mdx'`)
    bodies.push(`${locale}: ${varName}`)
  }
  entries.push(`  definePost(${id}Meta, { ${bodies.join(', ')} }),`)
}

const output = `// GENERATED by scripts/generate-post-registry.mjs — do not edit by hand.
${imports.join('\n')}
import { definePost } from './define'
import type { PostEntry } from './types'

export const registry: PostEntry[] = [
${entries.join('\n')}
]
`

writeFileSync(outFile, output)
console.log(`registry.generated.ts: ${slugs.length} post(s) registered`)
